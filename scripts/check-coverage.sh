#!/bin/bash
# Coverage gate: runs tests with coverage for every module and fails if
# any module's total coverage (across its tested packages — go tool
# cover's TOTAL line naturally excludes untestable wiring-only packages
# like main.go or generated mocks, since they never appear in a coverage
# profile without test files to execute them) drops below THRESHOLD.
#
# Usage: scripts/check-coverage.sh [threshold]
# Run from the repo root, inside WSL (needs the Go toolchain on PATH).
set -uo pipefail

# Self-contained PATH so this works the same from a fresh shell or CI,
# not just whatever interactive session happened to have Go on PATH
# already.
export PATH="$PATH:/usr/local/go/bin:$HOME/go/bin"

THRESHOLD="${1:-60}"
cd "$(dirname "$0")/.."

# cmd/rewardctl and mq are excluded as whole modules (see below); within
# the remaining modules, individual *packages* are filtered out of the
# coverage computation for the same underlying reason: each is either
# integration-tested rather than unit-tested, or generated/wiring code
# with no logic of its own to cover. Filtering package lines out of the
# profile (rather than excluding the whole module) still holds every
# *unit-testable* package in player-service/game-service/rewards-service
# to the real bar — these exclusions are specific and auditable, not an
# escape hatch for untested business logic to hide behind.
#   - internal/postgres, internal/dynamodb: covered by the build-tagged
#     integration tests (testcontainers, real Postgres/DynamoDB) in
#     services/*/internal/{postgres,dynamodb}/*_integration_test.go —
#     excluded here because -coverprofile only instruments the default
#     `go test ./...` run, which doesn't include those.
#   - internal/grpcclient: a handful of lines translating one call shape
#     to another gRPC call — same reasoning as mq below.
#   - internal/catalog/mocks: generated by mockgen; there's nothing to
#     cover in code that's never executed except via the mocked
#     interface it implements.
#   - every module's own root package (main.go): wiring, not logic —
#     already naturally near-impossible to unit test meaningfully.
EXCLUDE_PATTERN='/internal/postgres/|/internal/dynamodb/|/internal/grpcclient/|/internal/catalog/mocks/|services/player-service/main\.go|services/game-service/main\.go|services/rewards-service/main\.go'

# Two modules deliberately excluded entirely:
#   - cmd/rewardctl: a demo/CLI tool exercised manually
#     (./bin/rewardctl demo), not business logic — zero test files by
#     design.
#   - mq: a thin wrapper around the AWS SDK's SQS client. Its own event
#     schemas ARE tested (contract_test.go's golden-file tests), but
#     Client's methods (EnsureQueue/Publish/Consume) are a handful of
#     lines each calling straight into the SDK — unit-testing them would
#     mean mocking the SDK's own generated client, for little real
#     signal. This code was verified for real via the full docker-compose
#     flow in phase 6, which is the more meaningful check for "does this
#     actually talk to SQS correctly" than a mocked unit test would be.
MODULES="pkg/domain services/player-service services/game-service services/rewards-service"

fail=0
printf "%-40s %10s %10s\n" "MODULE" "COVERAGE" "STATUS"
printf "%-40s %10s %10s\n" "------" "--------" "------"

for mod in $MODULES; do
  profile="/tmp/coverage-$(echo "$mod" | tr '/' '_').out"
  if ! (cd "$mod" && go test ./... -coverprofile="$profile" >/tmp/test-output.log 2>&1); then
    printf "%-40s %10s %10s\n" "$mod" "n/a" "TEST FAIL"
    cat /tmp/test-output.log
    fail=1
    continue
  fi

  filtered="/tmp/coverage-filtered-$(echo "$mod" | tr '/' '_').out"
  head -1 "$profile" > "$filtered"                              # "mode: atomic" line go tool cover requires
  tail -n +2 "$profile" | grep -vE "$EXCLUDE_PATTERN" >> "$filtered"

  total=$(go tool cover -func="$filtered" 2>/dev/null | tail -1 | awk '{print $NF}' | tr -d '%')
  if [ -z "$total" ]; then
    printf "%-40s %10s %10s\n" "$mod" "n/a" "NO TESTS"
    continue
  fi

  # Bash can't do floating-point comparison natively; awk handles the
  # threshold check instead of trying to coerce $total into an integer.
  status="OK"
  if awk -v t="$total" -v th="$THRESHOLD" 'BEGIN { exit !(t < th) }'; then
    status="BELOW GATE"
    fail=1
  fi
  printf "%-40s %9s%% %10s\n" "$mod" "$total" "$status"
done

echo
if [ "$fail" -ne 0 ]; then
  echo "Coverage gate FAILED (threshold: ${THRESHOLD}%)"
  exit 1
fi
echo "Coverage gate passed (threshold: ${THRESHOLD}%)"
